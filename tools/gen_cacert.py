#!/usr/bin/env python3
"""Generates source/net/sx_cacert.c from a Mozilla-derived PEM bundle.

usage: gen_cacert.py <ca-bundle.pem> <source-label> > source/net/sx_cacert.c

The bundle is embedded as PEM text so mbedtls_x509_crt_parse() can load it as
it is.  Re-run it whenever the bundle is refreshed; the label and date it prints
are the record of where the roots came from.
"""
import re
import sys
import datetime

pem = open(sys.argv[1], encoding="ascii").read()
label = sys.argv[2]
blocks = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", pem, re.S)
seen = set()
uniq = []
for b in blocks:
    body = re.sub(r"\s+", "", b)
    if body in seen:
        continue
    seen.add(body)
    uniq.append(b)

lines = []
for b in uniq:
    for ln in b.splitlines():
        ln = ln.strip()
        if ln:
            lines.append(ln)

out = []
out.append("// Generated by tools/gen_cacert.py -- do not edit.")
out.append("// Source: %s" % label)
out.append("// Generated: %s, %d certificates." % (datetime.date.today().isoformat(), len(uniq)))
out.append('#include "sx_cacert.h"')
out.append("")
out.append("const char sx_cacert_pem[] =")
for ln in lines:
    out.append('    "%s\\n"' % ln)
out.append(";")
out.append("")
total = sum(len(l) + 1 for l in lines)
out.append("const unsigned sx_cacert_pem_len = %d;" % total)
out.append("")
sys.stdout.write("\n".join(out))
